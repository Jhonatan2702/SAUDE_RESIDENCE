def limite(tabela: str, coluna: str) -> int | None:
    for c in TABELAS[tabela]["cols"]:
        if c.nome == coluna and c.tipo == "txt":
            return c.tam
    return None


def _tipo(c: Col, motor: str) -> str:
    return {
        "sqlite": {"id": "INTEGER PRIMARY KEY AUTOINCREMENT", "txt": "TEXT", "longo": "TEXT", "int": "INTEGER", "real": "REAL"},
        "sqlserver": {"id": "INT IDENTITY(1,1) PRIMARY KEY", "txt": f"NVARCHAR({c.tam})", "longo": "NVARCHAR(MAX)",
                      "int": "INT", "real": "FLOAT"},
        "oracle": {"id": "NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY", "txt": f"VARCHAR2({c.tam} CHAR)",
                   "longo": "CLOB", "int": "NUMBER(10)", "real": "BINARY_DOUBLE"},
    }[motor][c.tipo]


def _coluna_ddl(c: Col, motor: str) -> str:
    partes = [c.nome, _tipo(c, motor)]
    if c.ci and motor == "sqlite":
        partes.append("COLLATE NOCASE")
    if c.ci and motor == "sqlserver":
        partes.append("COLLATE Latin1_General_100_CI_AI")
    if c.tipo == "id":
        return " ".join(partes)
    if motor == "oracle" and c.padrao is not None:  # Oracle exige DEFAULT antes de NOT NULL
        partes.append(f"DEFAULT {c.padrao}")
        if c.nn:
            partes.append("NOT NULL")
    else:
        if c.nn:
            partes.append("NOT NULL")
        if c.padrao is not None:
            partes.append(f"DEFAULT {c.padrao}")
    if c.unico:
        partes.append("UNIQUE")
    return " ".join(partes)


def ddl_tabela(nome: str, motor: str) -> str:
    t = TABELAS[nome]
    itens = [_coluna_ddl(c, motor) for c in t["cols"]]
    itens += [f"UNIQUE ({', '.join(u)})" for u in t.get("unicos", [])]
    return f"CREATE TABLE {nome} (\n    " + ",\n    ".join(itens) + "\n)"


