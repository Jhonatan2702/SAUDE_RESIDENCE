def _existentes(con: Conexao, tipo: str) -> set[str]:
    sql = {
        ("sqlite", "t"): "SELECT name FROM sqlite_master WHERE type = 'table'",
        ("sqlite", "i"): "SELECT name FROM sqlite_master WHERE type = 'index'",
        ("sqlserver", "t"): "SELECT name FROM sys.tables",
        ("sqlserver", "i"): "SELECT name FROM sys.indexes WHERE name IS NOT NULL",
        ("oracle", "t"): "SELECT table_name FROM user_tables",
        ("oracle", "i"): "SELECT index_name FROM user_indexes",
    }[(con.motor, tipo)]
    return {r[0].lower() for r in con.execute(sql)}


def criar_estrutura(con: Conexao) -> list[str]:
    """Cria as tabelas/índices que ainda não existem. Retorna as tabelas criadas."""
    criadas = []
    existentes = _existentes(con, "t")
    for nome in ORDEM_TABELAS:
        if nome not in existentes:
            con.raw.cursor().execute(ddl_tabela(nome, con.motor))
            criadas.append(nome)
    for nome in ORDEM_TABELAS:
        if nome in existentes and nome not in criadas:
            cur = con.raw.cursor()
            cur.execute(f"SELECT * FROM {nome} WHERE 1 = 0")
            atuais = {d[0].lower() for d in cur.description}
            for c in TABELAS[nome]["cols"]:
                if c.nome not in atuais and not c.nn and not c.unico:
                    kw = {"sqlite": "ADD COLUMN", "sqlserver": "ADD", "oracle": "ADD"}[con.motor]
                    con.raw.cursor().execute(f"ALTER TABLE {nome} {kw} {_coluna_ddl(c, con.motor)}")
    idx = _existentes(con, "i")
    for nome, tabela, coluna in INDICES:
        if nome not in idx:
            con.raw.cursor().execute(f"CREATE INDEX {nome} ON {tabela} ({coluna})")
    if con.motor == "oracle" and "usuarios" in criadas:
        con.raw.cursor().execute("CREATE UNIQUE INDEX ux_usuarios_lower ON usuarios (LOWER(usuario))")
    con.commit()
    return criadas


def contagens(con: Conexao) -> dict[str, int]:
    existentes = _existentes(con, "t")
    return {t: con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0] for t in ORDEM_TABELAS if t in existentes}


def versao(con: Conexao) -> str:
    sql = {"sqlite": "SELECT 'SQLite ' || sqlite_version()",
           "sqlserver": "SELECT @@VERSION",
           "oracle": "SELECT banner FROM v$version WHERE ROWNUM = 1"}[con.motor]
    try:
        return str(con.execute(sql).fetchone()[0]).splitlines()[0].strip()
    except Exception:
        return MOTORES[con.motor]


def criar_banco_sqlserver(cfg: dict) -> bool:
    """Cria o banco de dados no servidor se ele ainda não existir. Retorna True se criou."""
    nome = cfg["banco"].replace("]", "]]")
    con = abrir(cfg, banco_mestre=True)
    try:
        cur = con.raw.cursor()
        if cur.execute("SELECT 1 FROM sys.databases WHERE name = ?", cfg["banco"]).fetchone():
            return False
        cur.execute(f"CREATE DATABASE [{nome}] COLLATE Latin1_General_100_CI_AI")
        return True
    finally:
        con.close()


def testar(cfg: dict, criar_banco: bool = False) -> dict:
    """Conecta, informa versão e situação do esquema (e opcionalmente cria o banco no SQL Server)."""
    criou = criar_banco_sqlserver(cfg) if criar_banco and cfg.get("motor") == "sqlserver" else False
    con = abrir(cfg)
    try:
        tabelas = contagens(con)
        return {"versao": versao(con), "banco_criado": criou, "tabelas": tabelas,
                "estrutura_ok": all(t in tabelas for t in ORDEM_TABELAS), "registros": sum(tabelas.values())}
    finally:
        con.close()


def _copiar_tabela(origem: Conexao, destino: Conexao, tabela: str) -> int:
    rows = origem.execute(f"SELECT * FROM {tabela} ORDER BY id").fetchall()
    if not rows:
        return 0
    cols = [c.nome for c in TABELAS[tabela]["cols"]]
    sql = f"INSERT INTO {tabela} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))})"
    dados = [[r[c] for c in cols] for r in rows]
    if destino.motor == "sqlserver":
        destino.raw.cursor().execute(f"SET IDENTITY_INSERT {tabela} ON")
    for i in range(0, len(dados), 500):
        destino.executemany(sql, dados[i:i + 500])
    if destino.motor == "sqlserver":
        destino.raw.cursor().execute(f"SET IDENTITY_INSERT {tabela} OFF")
    elif destino.motor == "oracle":  # reposiciona a identidade após o maior id copiado
        destino.raw.cursor().execute(f"ALTER TABLE {tabela} MODIFY (id GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE))")
    return len(dados)


def migrar(origem_cfg: dict, destino_cfg: dict, apagar_destino: bool = False) -> dict:
    """Copia todas as tabelas (preservando ids) para o destino, criando a estrutura se necessário."""
    if mesma_config(origem_cfg, destino_cfg):
        raise ValueError("Origem e destino são o mesmo banco de dados.")
    origem, destino = abrir(origem_cfg), abrir(destino_cfg)
    try:
        criar_estrutura(destino)
        existente = contagens(destino)
        if sum(existente.values()) and not apagar_destino:
            raise ValueError("O banco de destino já contém dados. Marque a opção de substituir os dados para continuar.")
        try:
            if apagar_destino:
                for t in reversed(ORDEM_TABELAS):
                    destino.execute(f"DELETE FROM {t}")
            copiados = {t: _copiar_tabela(origem, destino, t) for t in ORDEM_TABELAS}
            conferidos = contagens(destino)
            divergentes = [t for t in ORDEM_TABELAS if conferidos.get(t) != copiados[t]]
            if divergentes:
                raise RuntimeError("Conferência de contagem falhou em: " + ", ".join(divergentes))
            destino.commit()
        except Exception:
            destino.rollback()
            raise
        return {"tabelas": copiados, "total": sum(copiados.values())}
    finally:
        origem.close()
        destino.close()
