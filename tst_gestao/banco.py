def _dpapi(dados: bytes, proteger: bool) -> bytes:
    import ctypes
    from ctypes import wintypes

    class Blob(ctypes.Structure):
        _fields_ = [("cbData", wintypes.DWORD), ("pbData", ctypes.POINTER(ctypes.c_char))]

    entrada = Blob(len(dados), ctypes.cast(ctypes.create_string_buffer(dados, len(dados)), ctypes.POINTER(ctypes.c_char)))
    saida = Blob()
    fn = ctypes.windll.crypt32.CryptProtectData if proteger else ctypes.windll.crypt32.CryptUnprotectData
    if not (fn(ctypes.byref(entrada), None, None, None, None, 0, ctypes.byref(saida))):
        raise OSError("DPAPI indisponível")
    try:
        return ctypes.string_at(saida.pbData, saida.cbData)
    finally:
        ctypes.windll.kernel32.LocalFree(saida.pbData)


def proteger_senha(senha: str) -> str:
    """Grava a senha protegida pelo Windows (DPAPI, vinculada ao usuário do Windows)."""
    if not senha:
        return ""
    try:
        return "dpapi:" + base64.b64encode(_dpapi(senha.encode("utf-8"), True)).decode()
    except Exception:
        return "b64:" + base64.b64encode(senha.encode("utf-8")).decode()


def revelar_senha(valor: str) -> str:
    if not valor:
        return ""
    tipo, _, resto = valor.partition(":")
    bruto = base64.b64decode(resto)
    return (_dpapi(bruto, False) if tipo == "dpapi" else bruto).decode("utf-8")


