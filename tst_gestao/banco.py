def mesma_config(a: dict, b: dict) -> bool:
    chaves = [k for k in CAMPOS_CFG if k not in ("driver",)]
    norm = lambda c: {k: (c.get(k) or "") for k in chaves}  # noqa: E731
    if a.get("motor", "sqlite") == "sqlite" and b.get("motor", "sqlite") == "sqlite":
        return Path(a.get("arquivo") or DB_PATH).resolve() == Path(b.get("arquivo") or DB_PATH).resolve()
    return norm(a) == norm(b)


# ---------------------------------------------------------------- tradução de SQL
_NOCASE = re.compile(r"([\w.]+)\s+COLLATE\s+NOCASE", re.I)
_VAZIO_DIF = re.compile(r"([\w.]+)\s*<>\s*''")
_VAZIO_IGUAL = re.compile(r"([\w.]+)\s*=\s*''")
_LIMITE = re.compile(r"\bLIMIT\s+(\d+|\?)(?:\s+OFFSET\s+(\d+|\?))?", re.I)
_SUBSTR = re.compile(r"\bsubstr\s*\(", re.I)


def _numerar(sql: str) -> str:
    saida, n, aspas = [], 0, False
    for ch in sql:
        if ch == "'":
            aspas = not aspas
        if ch == "?" and not aspas:
            n += 1
            saida.append(f":{n}")
        else:
            saida.append(ch)
    return "".join(saida)


def traduzir(sql: str, motor: str, params=()) -> tuple[str, list]:
    params = list(params or [])
    if motor == "sqlite":
        return sql, params
    if motor == "sqlserver":
        sql = _NOCASE.sub(r"\1", sql)
        sql = _SUBSTR.sub("SUBSTRING(", sql)
    else:
        sql = _NOCASE.sub(r"NLSSORT(\1, 'NLS_SORT=BINARY_CI')", sql)
        sql = _VAZIO_DIF.sub(r"\1 IS NOT NULL", sql)  # em Oracle '' é NULL
        sql = _VAZIO_IGUAL.sub(r"\1 IS NULL", sql)

    def pagina(m: re.Match) -> str:
        n, off = m.group(1), m.group(2)
        if n == "?" and off == "?":  # a ordem dos parâmetros se inverte: OFFSET vem primeiro
            i = sql[: m.start()].count("?")
            params[i], params[i + 1] = params[i + 1], params[i]
        return f"OFFSET {off or 0} ROWS FETCH NEXT {n} ROWS ONLY"

    sql = _LIMITE.sub(pagina, sql)
    return (_numerar(sql) if motor == "oracle" else sql), params


