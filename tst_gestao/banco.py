class Linha:
    """Linha de resultado com acesso por índice ou nome (compatível com sqlite3.Row)."""

    __slots__ = ("_nomes", "_valores")

    def __init__(self, nomes, valores):
        self._nomes, self._valores = nomes, valores

    def __getitem__(self, k):
        return self._valores[self._nomes.index(k) if isinstance(k, str) else k]

    def keys(self):
        return list(self._nomes)

    def __iter__(self):
        return iter(self._valores)

    def __len__(self):
        return len(self._valores)


class Cursor:
    def __init__(self, con: "Conexao"):
        self.con, self.cur, self._id, self._out = con, con.raw.cursor(), None, None

    def executar(self, sql: str, params=()):
        motor = self.con.motor
        sql, params = traduzir(sql, motor, params)
        self._id = self._out = None
        if motor == "oracle":
            m = re.match(r"\s*INSERT\s+INTO\s+(\w+)", sql, re.I)
            if m and m.group(1).lower() in TABELAS:
                self._out = self.cur.var(int)
                sql += f" RETURNING id INTO :{len(params) + 1}"
                params = params + [self._out]
        self.cur.execute(sql, params) if params else self.cur.execute(sql)
        return self

    @property
    def lastrowid(self):
        if self.con.motor == "oracle":
            v = self._out.getvalue() if self._out is not None else None
            return int(v[0]) if v else None
        row = self.con.raw.cursor().execute("SELECT CAST(@@IDENTITY AS INT)").fetchone()
        return row[0] if row else None

    @property
    def rowcount(self):
        return self.cur.rowcount

    def _linha(self, r):
        if r is None:
            return None
        return Linha([d[0].lower() for d in self.cur.description], list(r))

    def fetchone(self):
        return self._linha(self.cur.fetchone())

    def fetchall(self):
        return [self._linha(r) for r in self.cur.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())


class Conexao:
    def __init__(self, raw, motor: str):
        self.raw, self.motor = raw, motor

    @property
    def dual(self) -> str:
        return "FROM dual" if self.motor == "oracle" else ""

    def execute(self, sql: str, params=()):
        if self.motor == "sqlite":
            return self.raw.execute(sql, params)
        return Cursor(self).executar(sql, params)

    def executemany(self, sql: str, linhas):
        if self.motor == "sqlite":
            return self.raw.executemany(sql, linhas)
        linhas = list(linhas)
        if not linhas:
            return None
        sql2, _ = traduzir(sql, self.motor, linhas[0])
        cur = self.raw.cursor()
        cur.executemany(sql2, [list(r) for r in linhas])
        return cur

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        try:
            self.raw.close()
        except Exception:
            pass

    def __enter__(self):
        return self

    def __exit__(self, tipo, valor, tb):
        try:
            self.rollback() if tipo else self.commit()
        finally:
            self.close()
        return False


def _erros_integridade() -> tuple:
    erros = [sqlite3.IntegrityError]
    for nome in ("pyodbc", "oracledb"):
        try:
            erros.append(__import__(nome).IntegrityError)
        except Exception:
            pass
    return tuple(erros)


ErroIntegridade = _erros_integridade()


def drivers_sqlserver() -> list[str]:
    try:
        import pyodbc
    except ImportError:
        return []
    return sorted((d for d in pyodbc.drivers() if "SQL Server" in d), key=lambda d: ("Native" in d, d), reverse=True)


def _escolher_driver(cfg: dict) -> str:
    if cfg.get("driver"):
        return cfg["driver"]
    lista = drivers_sqlserver()
    for pref in ("ODBC Driver 18 for SQL Server", "ODBC Driver 17 for SQL Server", "ODBC Driver 13 for SQL Server"):
        if pref in lista:
            return pref
    if lista:
        return lista[0]
    raise RuntimeError("Nenhum driver ODBC do SQL Server encontrado. Instale o 'ODBC Driver 17/18 for SQL Server'.")


def abrir(cfg: dict | None = None, *, banco_mestre: bool = False) -> Conexao:
    cfg = cfg or ler_config()
    motor = cfg.get("motor", "sqlite")
    if motor == "sqlite":
        arquivo = Path(cfg.get("arquivo") or DB_PATH)
        arquivo.parent.mkdir(parents=True, exist_ok=True)
        raw = sqlite3.connect(arquivo, timeout=15)
        raw.row_factory = sqlite3.Row
        raw.execute("PRAGMA foreign_keys = ON")
        return Conexao(raw, "sqlite")
    senha = revelar_senha(cfg.get("senha_cifrada", ""))
    if motor == "sqlserver":
        try:
            import pyodbc
        except ImportError as exc:
            raise RuntimeError("Pacote 'pyodbc' não instalado (pip install pyodbc).") from exc
        servidor = cfg["servidor"] + (f",{cfg['porta']}" if cfg.get("porta") else "")
        cs = (f"DRIVER={{{_escolher_driver(cfg)}}};SERVER={servidor};DATABASE={'master' if banco_mestre else cfg['banco']};"
              f"Encrypt={'yes' if cfg.get('criptografar') else 'no'};TrustServerCertificate={'yes' if cfg.get('confiar_certificado', True) else 'no'};"
              "MARS_Connection=no;")
        cs += "Trusted_Connection=yes;" if cfg.get("autenticacao") == "windows" else f"UID={cfg['usuario']};PWD={{{senha.replace('}', '}}')}}};"
        return Conexao(pyodbc.connect(cs, timeout=10, autocommit=banco_mestre), "sqlserver")
    try:
        import oracledb
    except ImportError as exc:
        raise RuntimeError("Pacote 'oracledb' não instalado (pip install oracledb).") from exc
    oracledb.defaults.fetch_lobs = False
    dsn = cfg.get("dsn") or f"{cfg['servidor']}:{cfg.get('porta') or 1521}/{cfg['servico']}"
    return Conexao(oracledb.connect(user=cfg["usuario"], password=senha, dsn=dsn, tcp_connect_timeout=10), "oracle")


def conectar() -> Conexao:
    return abrir(ler_config())


