def ler_config() -> dict:
    env = os.environ.get("TST_DB_MOTOR")
    if env == "sqlite":
        return cfg_padrao()
    try:
        mtime = CONFIG_PATH.stat().st_mtime_ns
    except OSError:
        return cfg_padrao()
    with _trava:
        if _cache["mtime"] != mtime:
            try:
                _cache["cfg"] = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                _cache["cfg"] = cfg_padrao()
            _cache["mtime"] = mtime
        return dict(_cache["cfg"])


def gravar_config(cfg: dict) -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    limpo = {k: cfg[k] for k in CAMPOS_CFG if cfg.get(k) not in (None, "")}
    if cfg.get("senha_cifrada") or cfg.get("senha"):
        limpo["senha_cifrada"] = cfg.get("senha_cifrada") or proteger_senha(cfg["senha"])
    if limpo.get("motor") in (None, "sqlite") and not limpo.get("arquivo"):
        CONFIG_PATH.unlink(missing_ok=True)
    else:
        tmp = CONFIG_PATH.with_suffix(".tmp")
        tmp.write_text(json.dumps(limpo, ensure_ascii=False, indent=2), encoding="utf-8")
        os.replace(tmp, CONFIG_PATH)
    with _trava:
        _cache["mtime"] = None


def normalizar_cfg(bruto: dict, salva: dict | None = None) -> dict:
    """Valida o formulário; reaproveita a senha salva quando o campo vem em branco."""
    motor = bruto.get("motor") or "sqlite"
    if motor not in MOTORES:
        raise ValueError("Motor de banco inválido.")
    cfg = {"motor": motor}
    txt = lambda k: str(bruto.get(k) or "").strip()  # noqa: E731
    if motor == "sqlite":
        if txt("arquivo"):
            cfg["arquivo"] = txt("arquivo")
        return cfg
    senha = bruto.get("senha") or ""
    if motor == "sqlserver":
        if not txt("servidor") or not txt("banco"):
            raise ValueError("Informe o servidor e o nome do banco de dados.")
        cfg.update(servidor=txt("servidor"), banco=txt("banco"), autenticacao="windows" if txt("autenticacao") == "windows" else "sql",
                   driver=txt("driver"), criptografar=bool(bruto.get("criptografar")),
                   confiar_certificado=bool(bruto.get("confiar_certificado", True)))
        if txt("porta"):
            cfg["porta"] = txt("porta")
        if cfg["autenticacao"] == "sql":
            if not txt("usuario"):
                raise ValueError("Informe o usuário do banco.")
            cfg["usuario"] = txt("usuario")
    else:
        if not txt("dsn") and (not txt("servidor") or not txt("servico")):
            raise ValueError("Informe servidor e nome do serviço (ou um DSN completo).")
        if not txt("usuario"):
            raise ValueError("Informe o usuário (schema) do Oracle.")
        cfg.update(usuario=txt("usuario"), servidor=txt("servidor"), porta=txt("porta") or "1521", servico=txt("servico"), dsn=txt("dsn"))
    if cfg.get("usuario"):
        if senha:
            cfg["senha_cifrada"] = proteger_senha(senha)
        elif salva and salva.get("motor") == motor and salva.get("usuario") == cfg["usuario"] and salva.get("senha_cifrada"):
            cfg["senha_cifrada"] = salva["senha_cifrada"]
        else:
            raise ValueError("Informe a senha do banco.")
    return {k: v for k, v in cfg.items() if v not in (None, "")}


