import os
import tempfile

os.environ["TST_DATA_DIR"] = tempfile.mkdtemp()

from tst_gestao import banco  # noqa: E402
from tests.test_integracoes import admin  # noqa: E402


def test_traduzir_sqlserver():
    sql, p = banco.traduzir("SELECT a FROM t WHERE substr(d,1,7) = ? ORDER BY a COLLATE NOCASE LIMIT ? OFFSET ?", "sqlserver", ["x", 10, 20])
    assert "SUBSTRING(" in sql and "NOCASE" not in sql
    assert "OFFSET ? ROWS FETCH NEXT ? ROWS ONLY" in sql
    assert list(p) == ["x", 20, 10]


def test_traduzir_oracle():
    sql, p = banco.traduzir("SELECT a FROM t WHERE b = ? AND c <> '' ORDER BY a LIMIT 5", "oracle", ["x"])
    assert ":1" in sql and "?" not in sql
    assert "c IS NOT NULL" in sql
    assert "FETCH NEXT 5 ROWS ONLY" in sql


def test_ddl_todos_os_motores():
    for motor in ("sqlite", "sqlserver", "oracle"):
        for t in banco.ORDEM_TABELAS:
            ddl = banco.ddl_tabela(t, motor)
            assert t in ddl.lower()
    assert "IDENTITY(1,1)" in banco.ddl_tabela("pacientes", "sqlserver")
    assert "GENERATED BY DEFAULT" in banco.ddl_tabela("pacientes", "oracle")


def test_migrar_sqlite_para_sqlite_e_api():
    a = admin()
    a.post("/api/pacientes", json={"codigo": "M1", "nome": "Mara", "data_admissao": "2026-01-02", "data_alta": "2026-02-01", "motivo_alta": "Alta clínica"})
    destino = {"motor": "sqlite", "arquivo": os.path.join(os.environ["TST_DATA_DIR"], "copia.db")}

    r = a.post("/api/banco/testar", json={"cfg": destino})
    assert r.status_code == 200 and r.get_json()["estrutura_ok"] is False

    r = a.post("/api/banco/migrar", json={"cfg": destino})
    j = r.get_json()
    assert r.status_code == 200 and j["tabelas"]["pacientes"] >= 1

    # destino já populado: exige confirmação de substituição
    assert a.post("/api/banco/migrar", json={"cfg": destino}).status_code == 400
    assert a.post("/api/banco/migrar", json={"cfg": destino, "apagar_destino": True}).status_code == 200

    # origem == destino é bloqueado
    assert a.post("/api/banco/migrar", json={"cfg": {"motor": "sqlite"}}).status_code == 400
    assert a.get("/api/banco").get_json()["cfg"]["motor"] == "sqlite"


def test_api_banco_exige_admin_e_nao_vaza_senha():
    cfg = banco.normalizar_cfg({"motor": "oracle", "servidor": "h", "servico": "s", "usuario": "u", "senha": "segredo!"})
    assert "segredo!" not in str(cfg) and "segredo!" not in str(banco.cfg_publica(cfg))
    assert banco.revelar_senha(cfg["senha_cifrada"]) == "segredo!"
    anon = admin().application.test_client()
    assert anon.get("/api/banco").status_code in (401, 302)
